#!/usr/bin/env python3
"""Regenerate the zip_centroids migration from the Census ZCTA Gazetteer.

Usage: python3 supabase/scripts/build_zip_centroids.py > supabase/migrations/<ts>_zip_centroids.sql
"""
import csv
import io
import sys
import urllib.request
import zipfile

YEAR = 2024
URL = (
    f"https://www2.census.gov/geo/docs/maps-data/data/gazetteer/{YEAR}_Gazetteer/"
    f"{YEAR}_Gaz_zcta_national.zip"
)
ROWS_PER_LINE = 8
LINES_PER_INSERT = 250


def rows():
    with urllib.request.urlopen(URL) as resp:
        archive = zipfile.ZipFile(io.BytesIO(resp.read()))
    text = archive.read(archive.namelist()[0]).decode("utf-8")
    reader = csv.DictReader(io.StringIO(text), delimiter="\t")
    for row in reader:
        row = {k.strip(): v.strip() for k, v in row.items()}
        yield row["GEOID"], float(row["INTPTLAT"]), float(row["INTPTLONG"])


def main():
    data = sorted(rows())
    out = sys.stdout
    out.write(
        f"-- U.S. ZIP centroids for ZIP-code fallback when GPS is off (T-11).\n"
        f"-- Source: U.S. Census Bureau {YEAR} Gazetteer, ZCTA internal points (public domain).\n"
        f"-- Generated by supabase/scripts/build_zip_centroids.py; do not edit by hand.\n"
        f"-- ZCTAs approximate ZIPs: PO-box-only and some business ZIPs have no centroid.\n\n"
        "create table public.zip_centroids (\n"
        "  zip text primary key check (zip ~ '^[0-9]{5}$'),\n"
        "  geo_lat numeric(9, 6) not null check (geo_lat between -90 and 90),\n"
        "  geo_lng numeric(9, 6) not null check (geo_lng between -180 and 180)\n"
        ");\n\n"
        "alter table public.zip_centroids enable row level security;\n"
        "revoke all on public.zip_centroids from anon, authenticated;\n"
        "grant select on public.zip_centroids to anon, authenticated;\n"
        "create policy zip_centroids_select_all on public.zip_centroids\n"
        "  for select to anon, authenticated using (true);\n"
    )
    lines = [
        ", ".join(f"('{z}', {lat:.6f}, {lng:.6f})" for z, lat, lng in data[i : i + ROWS_PER_LINE])
        for i in range(0, len(data), ROWS_PER_LINE)
    ]
    for i in range(0, len(lines), LINES_PER_INSERT):
        chunk = lines[i : i + LINES_PER_INSERT]
        out.write("\ninsert into public.zip_centroids (zip, geo_lat, geo_lng) values\n")
        out.write(",\n".join(chunk) + ";\n")


if __name__ == "__main__":
    main()
